// Fetches Instrument Serif, which is not in the `geist` package.
//
// One copy of each file lives in `assets/fonts`. The browser loads it through
// `next/font/local`, and the Open Graph renderer needs the same bytes inlined as
// base64 because the Worker has no filesystem at runtime.
//
// Instrument Serif is licensed under the SIL Open Font License 1.1.

import { mkdir, writeFile } from "node:fs/promises";
import { join } from "node:path";

const BASE = "https://raw.githubusercontent.com/google/fonts/main/ofl/instrumentserif";
const FILES = {
  regular: "InstrumentSerif-Regular.ttf",
  italic: "InstrumentSerif-Italic.ttf",
};

const root = process.cwd();
const fontDir = join(root, "assets/fonts");

async function download(name, target) {
  const res = await fetch(`${BASE}/${name}`);
  if (!res.ok) throw new Error(`${name}: ${res.status}`);
  const bytes = Buffer.from(await res.arrayBuffer());
  await writeFile(target, bytes);
  return bytes;
}

await mkdir(fontDir, { recursive: true });

let regular;
for (const [slug, name] of Object.entries(FILES)) {
  const bytes = await download(name, join(fontDir, `instrument-serif-${slug}.ttf`));
  if (slug === "regular") regular = bytes;
  console.log(`${slug}: ${bytes.length} bytes`);
}

await writeFile(
  join(root, "src/app/og-font.ts"),
  `// Generated by scripts/fetch-fonts.mjs. Do not edit.\n` +
    `export const displayFontBase64 =\n  "${regular.toString("base64")}";\n`,
);
console.log("b64: src/app/og-font.ts");
